"""Tests for the explicit GAUSS-style Halton generator (_halt_draws)."""

from __future__ import annotations

from pathlib import Path
from types import SimpleNamespace

import numpy as np
import pytest

from pybhatlib.mixed._draws import ScipyHaltonDrawSource
from pybhatlib.mixed._halt_draws import ExplicitHaltonDrawSource, gethalton

FIXTURE = Path(__file__).parent.parent / "fixtures" / "mixed" / "halton" / "gethalton_baseline.npz"
CASES = [(5, 4, 3, 1), (7, 10, 5, 0), (4, 5, 16, 1), (3, 4, 48, 0)]  # nrep, nobs, ndim, corbreak


def _gh(nrep, nobs, nd, cb, normal):
    return gethalton(nrep, nobs, nd, np.zeros(nd), np.eye(nd), 1, normal=normal, corbreak=cb)


@pytest.mark.parametrize("k", range(len(CASES)))
def test_bit_identical_to_pre_vectorization_output(k):
    """Fixtures were generated by the original per-point loop implementation."""
    ref = np.load(FIXTURE)
    nrep, nobs, nd, cb = CASES[k]
    assert np.array_equal(_gh(nrep, nobs, nd, cb, 0), ref[f"raw{k}"])
    assert np.array_equal(_gh(nrep, nobs, nd, cb, 1), ref[f"z{k}"])


def test_unscrambled_matches_textbook_halton_after_burnin():
    burnin = 10
    n = 6
    raw = gethalton(n, 1, 2, np.zeros(2), np.eye(2), 1, normal=0, corbreak=0)

    def radical_inverse(i, b):
        f, r = 1.0, 0.0
        while i > 0:
            f /= b
            r += f * (i % b)
            i //= b
        return r

    # point index i (1-based) = burnin + 1 + row
    for row in range(n):
        i = burnin + 1 + row
        assert raw[row, 0] == pytest.approx(radical_inverse(i, 2), abs=1e-15)
        assert raw[row, 1] == pytest.approx(radical_inverse(i, 3), abs=1e-15)
    # first values explicitly: indices 11,12,13 in base 2 -> 13/16, 3/16, 11/16
    assert raw[0, 0] == pytest.approx(0.8125)
    assert raw[1, 0] == pytest.approx(0.1875)
    assert raw[2, 0] == pytest.approx(0.6875)


def test_draw_source_shape_and_ordering():
    n_rep, n_ind, n_rnd = 6, 5, 4
    src = ExplicitHaltonDrawSource()
    d = src.draws(n_ind, n_rnd, n_rep)
    assert d.shape == (n_rep, n_ind, n_rnd)
    flat = gethalton(n_rep, n_ind, n_rnd, np.zeros(n_rnd), np.eye(n_rnd), 1, normal=1)
    for r in range(n_rep):
        for i in range(n_ind):
            assert np.array_equal(d[r, i], flat[i * n_rep + r])


def test_deterministic_across_seeds():
    a = ExplicitHaltonDrawSource(seed=1).draws(4, 3, 5)
    b = ExplicitHaltonDrawSource(seed=999).draws(4, 3, 5)
    assert np.array_equal(a, b)


def test_dimension_limit_falls_back_to_scipy():
    src = ExplicitHaltonDrawSource(seed=3)
    with pytest.warns(UserWarning, match="Reverting to ScipyHaltonDrawSource"):
        d = src.draws(3, 17, 4)  # corbreak=1 supports at most 16 dims
    assert isinstance(src._fallback, ScipyHaltonDrawSource)
    assert d.shape == (4, 3, 17)


def test_run_gt_1_warns_when_deterministic():
    with pytest.warns(UserWarning, match="deterministic"):
        ExplicitHaltonDrawSource().draws(3, 2, 4, run=2)


def test_invalid_draw_method_raises():
    from pybhatlib.models.mixmnl._mixmnl_model import MixMNLModel

    model = object.__new__(MixMNLModel)
    model.control = SimpleNamespace(draw_method="bogus", draw_seed=1)
    with pytest.raises(ValueError, match="draw_method"):
        model._make_draw_source(2, 5, 3)
    model.control = SimpleNamespace(draw_method="explicit", draw_seed=1)
    assert isinstance(model._make_draw_source(2, 5, 3), ExplicitHaltonDrawSource)
